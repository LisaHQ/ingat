"""Version gate (ARCHITECTURE §3.6, ADR-0014): which gate tier may run on this Engine and platform build."""

import re
from importlib.resources import files
from typing import Any

from ingat import brand
from ingat.model import records
from ingat.model.errors import CannotRun

TIER0, TIER1, TIER2 = 0, 1, 2  # read-only; online backup and verify; everything else
MIN_API = (1, 43)
BUILD_KEYS = tuple("os_release engine git_commit build_time containerd runc kernel storage_driver architecture".split())
_ARCH = {"x86_64": "amd64", "aarch64": "arm64"}
_VERSION = re.compile(r"^(\d+)\.(\d+)")


def _version(text: object) -> tuple[int, int] | None:
    m = _VERSION.match(str(text))
    return (int(m[1]), int(m[2])) if m else None


def _arch(name: object) -> str:
    return _ARCH.get(str(name), str(name))


def _key(build: dict[str, Any]) -> dict[str, Any]:
    return {k: _arch(build.get(k)) if k == "architecture" else build.get(k) for k in BUILD_KEYS}


def load_tested() -> list[dict[str, Any]]:
    """The release's `tested.json` (package data, generated by CI)."""
    doc = records.loads((files(brand) / "tested.json").read_bytes())
    if not isinstance(doc, list) or not all(isinstance(e, dict) for e in doc):
        raise CannotRun("tested.json must be a list of objects", code="untested-platform")
    return doc


def committed_certifications() -> list[dict[str, Any]]:
    """Platform certifications embedded in the release (`support/hosts/*.json`, package data)."""
    hosts = files(brand) / "support" / "hosts"
    if not hosts.is_dir():
        return []
    docs = [records.loads(p.read_bytes()) for p in hosts.iterdir() if p.name.endswith(".json")]
    if not all(isinstance(d, dict) for d in docs):
        raise CannotRun("support/hosts certifications must be JSON objects", code="uncertified")
    return docs


def platform_build(host_facts: dict[str, Any]) -> dict[str, Any]:
    """The certification key, taken from a host record's `versions` and `facts`."""
    flat = {**host_facts.get("versions", {}), **host_facts.get("facts", {})}
    return {k: flat.get(k) for k in BUILD_KEYS}


def check(
    tier: int,
    *,
    engine_version: str,
    api_version: str,
    arch: str,
    build: dict[str, Any],
    certifications: list[dict[str, Any]],
    tested: list[dict[str, Any]],
) -> list[str]:
    """Warnings for gate tier 1; raises CannotRun when `tier` may not run here. Committed certifications count too."""
    if tier == TIER0:
        return []
    api = _version(api_version)
    if api is None or api < MIN_API:
        raise CannotRun(
            f"Engine API {api_version} is below the minimum {MIN_API[0]}.{MIN_API[1]}", code="untested-platform"
        )
    engine = _version(engine_version)
    if engine is None or not any(
        _version(t.get("engine")) == engine and _arch(t.get("arch")) == _arch(arch) for t in tested
    ):
        text = f"Engine {engine_version} on {_arch(arch)} is not a tested combination of this release"
        if tier == TIER1:
            return [text]
        raise CannotRun(text, code="untested-platform")
    if tier == TIER1:
        return []
    selftest = f"{brand.CLI} selftest --host"
    missing = [k for k in BUILD_KEYS if not build.get(k)]  # an empty value identifies no build
    if missing:
        raise CannotRun(f"platform build facts missing: {', '.join(missing)}", code="uncertified", next=selftest)
    want = _key(build)
    if not any(
        c.get("kind") == "selftest"
        and c.get("result") == "PASS"
        and isinstance(c.get("build"), dict)
        and _key(c["build"]) == want
        for c in [*certifications, *committed_certifications()]
    ):
        raise CannotRun("no host certification for this platform build", code="uncertified", next=selftest)
    return []
